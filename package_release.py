"""Build the universal installer and source ZIP using Python 3.8+ only."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import shutil
import zipfile

ROOT = Path(__file__).resolve().parent
MEL_NAME = "HTools_QuadDrawThrough_v1.0_Install.mel"
PREFIX = "HTools_QuadDrawThrough"
ROOT_SOURCE = (
    ".gitattributes", ".gitignore", "LICENSE", "README.md", "README.zh-CN.md",
    "CHANGELOG.md", "CONTRIBUTING.md", "install.py",
    "HTools_QuadDrawThrough_Install_v10.py", "package_manifest.json",
    "package_release.py", MEL_NAME,
)


def zip_bytes(files):
    """Stable file order, timestamps and permissions for reproducible builds."""
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data, compresslevel=9)
    return output.getvalue()


def standalone_mel(payload, license_text):
    """ASCII MEL containing the readable loader, license and encoded runtime."""
    encoded = base64.b64encode(payload).decode("ascii")
    code = '''import base64, io, os, shutil, tempfile, zipfile
_ht_parent = os.path.realpath(tempfile.gettempdir())
_ht_temp = os.path.realpath(tempfile.mkdtemp(prefix='HTools_QDT_install_', dir=_ht_parent))
try:
    _ht_payload = base64.b64decode(%r)
    with zipfile.ZipFile(io.BytesIO(_ht_payload)) as _ht_zip:
        for _ht_name in _ht_zip.namelist():
            if _ht_name.startswith(('/', '\\\\')) or '..' in _ht_name.replace('\\\\', '/').split('/') or ':' in _ht_name:
                raise RuntimeError('Invalid installer payload path')
        _ht_zip.extractall(_ht_temp)
    _ht_file = os.path.join(_ht_temp, 'HTools_QuadDrawThrough_Install_v10.py')
    _ht_ns = {'__file__': _ht_file, '__name__': 'htools_standalone_mel_install'}
    with open(_ht_file, 'rb') as _ht_stream:
        _ht_code = compile(_ht_stream.read(), 'HTools_QuadDrawThrough_Install_v10.py', 'exec')
    eval(_ht_code, _ht_ns)
    _ht_ns['onMayaDroppedPythonFile']()
finally:
    if os.path.dirname(os.path.realpath(_ht_temp)) == _ht_parent and os.path.basename(_ht_temp).startswith('HTools_QDT_install_'):
        shutil.rmtree(_ht_temp)
''' % encoded
    compile(code, "<standalone MEL installer>", "exec")
    chunks = [json.dumps(code[i:i + 1000]) for i in range(0, len(code), 1000)]
    header = (
        "// HTools_QuadDrawThrough 1.0 - universal standalone installer.\n"
        "// SPDX-License-Identifier: MIT\n"
        "// Generated by package_release.py. Edit the Python source and rebuild.\n"
        "// Drag this file into Maya, or load and execute it in Script Editor (MEL).\n"
        "// No adjacent files or fixed installation paths are required.\n//\n"
    )
    header += "\n".join("// " + line for line in license_text.splitlines()) + "\n\n"
    return (header + "python(\n    " + "\n    + ".join(chunks) + "\n);\n").encode("ascii")


def source_paths():
    paths = [ROOT / name for name in ROOT_SOURCE]
    paths += sorted((ROOT / "qd_through").glob("*.py"))
    paths += sorted((ROOT / "tests").glob("*.py"))
    paths += [ROOT / "tests" / "requirements-python2.txt"]
    paths += sorted((ROOT / "docs").glob("*.md"))
    return paths


def build(output):
    manifest = json.loads((ROOT / "package_manifest.json").read_text(encoding="utf-8"))
    if manifest["version"] != "1.0.0" or manifest["license"] != "MIT":
        raise ValueError("Update release filenames and metadata together before changing version/license")
    if manifest["maya_min"] != 2018 or manifest["maya_max"] != 2027:
        raise ValueError("Universal release compatibility metadata does not match its name")
    runtime_paths = [ROOT / name for name in (
        "install.py", "HTools_QuadDrawThrough_Install_v10.py", "package_manifest.json", "LICENSE")]
    runtime_paths += sorted((ROOT / "qd_through").glob("*.py"))
    runtime = {path.relative_to(ROOT).as_posix(): path.read_bytes() for path in runtime_paths}
    for name, data in runtime.items():
        if name.endswith(".py"):
            compile(data, name, "exec")
    mel = standalone_mel(zip_bytes(runtime), (ROOT / "LICENSE").read_text(encoding="ascii"))
    (ROOT / MEL_NAME).write_bytes(mel)
    output.mkdir(parents=True, exist_ok=True)
    mel_target = output / MEL_NAME
    if mel_target.resolve() != (ROOT / MEL_NAME).resolve():
        shutil.copyfile(ROOT / MEL_NAME, mel_target)
    source_name = "HTools_QuadDrawThrough_v1.0_Source.zip"
    sources = {PREFIX + "/" + path.relative_to(ROOT).as_posix(): path.read_bytes() for path in source_paths()}
    (output / source_name).write_bytes(zip_bytes(sources))
    artifacts = [MEL_NAME, source_name]
    checksums = []
    for name in artifacts:
        data = (output / name).read_bytes()
        if name.endswith(".zip"):
            with zipfile.ZipFile(io.BytesIO(data)) as archive:
                if archive.testzip() is not None:
                    raise RuntimeError("Corrupt archive: " + name)
        checksums.append(hashlib.sha256(data).hexdigest() + "  " + name)
        print(name + " (" + str(len(data)) + " bytes)")
    (output / "SHA256SUMS.txt").write_text("\n".join(checksums) + "\n", encoding="ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "dist", help="Artifact directory; default: dist/")
    build(parser.parse_args().output.resolve())
